const number = (value: number) => formatNumber("ru", value);

// "1 день", "3 дня", "5 дней"; fractions take the "few" form ("1,5 дня").
function word(count: number, one: string, few: string, many: string): string {
  return pluralForm("ru", count, { few, many, one, other: few });
}

function p(count: number, one: string, few: string, many: string): string {
  return `${number(count)} ${word(count, one, few, many)}`;
}

